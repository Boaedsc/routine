def dates_mobiles(annee):
    """Dates mobiles explicitement précisées dans la source structurée."""
    from calendrier import paques
    p = paques(annee)
    # Dimanche entre Noël et l'Épiphanie (strictement après Noël).
    x = date(annee, 12, 26)
    nom_jesus = next((date(annee, 1, j) for j in range(2, 7)
                      if date(annee, 1, j).weekday() == 6), None)
    if nom_jesus is None:
        nom_jesus = date(annee, 1, 2)
    epiphanie = date(annee, 1, 6)
    famille = epiphanie + timedelta(days=(6-epiphanie.weekday()) % 7 or 7)
    passion = p - timedelta(days=14)
    douleur = passion + timedelta(days=(4-passion.weekday()) % 7 or 7)
    christ_roi = date(annee, 10, 31)
    while christ_roi.weekday() != 6:
        christ_roi -= timedelta(days=1)
    defunts = date(annee, 11, 3) if date(annee, 11, 2).weekday() == 6 else date(annee, 11, 2)
    return [(nom_jesus, "II", "Saint Nom de Jésus"),
            (famille, "II", "Sainte Famille"),
            (douleur, "Comm", "Sept Douleurs de la Vierge"),
            (christ_roi, "I", "Christ-Roi"),
            (defunts, "I", "Commémoration des fidèles défunts")]

def verifier_reference():
    """Compare la référence aux entrées fixes de calendrier.SANCTORAL."""
    import calendrier
    ecarts = []
    for cle, (rang_ref, libelle) in sorted(REF_1962.items()):
        entree = calendrier.SANCTORAL.get(cle)
        if entree is None:
            ecarts.append((cle, "absente", rang_ref, libelle, None))
            continue
        rang_actuel = calendrier.classe_vers_rang(entree[1], entree[2])
        if rang_actuel != rang_ref:
            ecarts.append((cle, "rang", rang_ref, libelle, rang_actuel))
        if not calendrier.noms_correspondent(libelle, entree[0]):
            ecarts.append((cle, "nom", rang_ref, libelle, entree[0]))
    for cle, entree in sorted(calendrier.SANCTORAL.items()):
        if cle not in REF_1962 and "commemoratio" not in entree[2]:
            ecarts.append((cle, "date_extra", None, None, entree[0]))
    return ecarts
